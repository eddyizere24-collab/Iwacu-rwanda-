#!/usr/bin/env bash
# Builds sql/apply_all.sql: ONE file to paste into the Supabase SQL editor (migrations 001, 002, 003, then the emergency seed).
# Never edit apply_all.sql by hand; change the source files and run this script (tests/unit/sql-bundle.test.ts checks they agree).
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "-- IWACU RWANDA: all database setup in one paste. GENERATED by scripts/build-sql-bundle.sh — do not edit."
  echo "-- Order: 001_core_schema, 002_leaders_workflow, 003_contacts_roles_emergency, seed/001_emergency_national."
  echo "-- Run it on a Supabase BRANCH or a throw-away project first. Extensions postgis and ltree must be enabled."
  for f in sql/migrations/001_core_schema.sql sql/migrations/002_leaders_workflow.sql sql/migrations/003_contacts_roles_emergency.sql sql/seed/001_emergency_national.sql; do
    echo; echo "-- ===================== $f ====================="; cat "$f"
  done
} > sql/apply_all.sql
echo "wrote sql/apply_all.sql ($(wc -l < sql/apply_all.sql) lines)"
